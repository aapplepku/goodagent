"""Build the concise pre-launch report without selecting favorable cases."""

import argparse
import gzip
import json
from pathlib import Path
from typing import Any

from open_commerce.controller.benchmark import SCENARIOS, BenchmarkEvidence, summarize
from open_commerce.core.types import canonical_hash
from open_commerce.search.benchmark import distribution

ROOT = Path(__file__).resolve().parents[1]
CONTROLLER = ROOT / "examples/eval/results/controller-v2-durable.json.gz"
SEARCH = ROOT / "examples/eval/results/search-v2-live.json"
OUTPUT = ROOT / "docs/BENCHMARKS.md"


def render() -> str:
    controller = json.loads(gzip.decompress(CONTROLLER.read_bytes()))
    evidence = BenchmarkEvidence.model_validate(
        {key: controller[key] for key in ("benchmark_version", "rows", "failures")}
    )
    cases = {
        (scenario, variant, seed, arm)
        for scenario in SCENARIOS
        for variant in ("standard", "inventory_infeasible")
        for seed in range(100)
        for arm in ("no_intervention", "goal_conditioned_controller")
    }
    actual = {(row.scenario, row.variant, row.seed, row.arm) for row in evidence.rows}
    if (
        not controller["complete"]
        or evidence.failures
        or len(evidence.rows) != len(cases)
        or actual != cases
        or any(row.horizon_days != 30 or len(row.daily) != 30 for row in evidence.rows)
        or evidence.evidence_hash != controller["quality_evidence_hash"]
        or summarize(evidence.rows) != controller["summary"]
    ):
        raise ValueError("Controller evidence is incomplete or changed")
    search = json.loads(SEARCH.read_text())
    quality = [{k: v for k, v in row.items() if k != "latency_ms"} for row in search["queries"]]
    modes = {"sparse", "dense", "hybrid", "hybrid_reranked", "hybrid_boosted"}
    if (
        canonical_hash(quality) != search["quality_evidence_hash"]
        or search["retrieval_backend"] != "live_qdrant"
        or {row["mode"] for row in search["results"]} != modes
        or len(search["results"]) != len(modes)
        or len(quality) != search["query_count"] * len(modes)
    ):
        raise ValueError("Search evidence is incomplete or changed")
    for group in search["results"]:
        queries = [row for row in search["queries"] if row["mode"] == group["mode"]]
        if len({row["query_id"] for row in queries}) != search["query_count"]:
            raise ValueError("Missing or duplicated query in a search mode")
        for metric in ("ndcg_at_10", "recall_at_20", "latency_ms"):
            recomputed = distribution([float(row[metric]) for row in queries])
            # Raw per-query values were rounded to six decimals before archival.
            if any(
                abs(float(value) - float(group[metric][key])) > 0.0000011
                for key, value in recomputed.items()
            ):
                raise ValueError("Search distribution differs from raw queries")
        count = sum(len(row["results"]) for row in queries)
        bad = sum(
            len({item.split(":", 1)[0] for item in row["hard_violations"]}) for row in queries
        )
        satisfaction = (count - bad) / count if count else 1
        if abs(satisfaction - float(group["hard_constraint_satisfaction"])) > 0.0000011:
            raise ValueError("Search hard satisfaction differs from raw queries")
    lines = [
        "# Synthetic Benchmark Overview",
        "",
        "Frozen reference measurements, not a new run or real-commerce lift claim.",
        "All modes, seeds, scenarios and arms are included, including no-action outcomes.",
        "Generated by `scripts/render-preview-benchmarks.py`; do not hand-edit values.",
        "",
        "## Search",
        "",
        f"{search['query_count']} synthetic queries, {search['catalog_count']} products, seed 42; "
        f"live Qdrant {search['qdrant_version']}. "
        "Tiny incomplete judgments, no significance claim.",
        "Dense uses signed hashing, not a neural embedding model. Reranking is deterministic.",
        "",
        "| Mode | Mean NDCG@10 | Mean Recall@20 | Hard satisfaction | p50 / p95 ms |",
        "| --- | ---: | ---: | ---: | ---: |",
    ]
    for row in search["results"]:
        lines.append(
            f"| {row['mode']} | {row['ndcg_at_10']['mean']} | {row['recall_at_20']['mean']} | "
            f"{row['hard_constraint_satisfaction']} | "
            f"{row['latency_ms']['p50']} / {row['latency_ms']['p95']} |"
        )
    lines.extend(
        [
            "",
            "Reranking did not improve aggregate NDCG over hybrid in this fixture. Boosting",
            "changed eligible results without improving this quality aggregate. One impossible",
            "price query returns nothing and scores zero. Latency excludes indexing and API/PG",
            "loading; it varies with hardware/network and is not an application SLA.",
            "[Per-query evidence and methods](benchmarks/search-v2.md).",
            "",
            "## Controller",
            "",
            "1,200 matched rows: 100 seeds x three scenarios x two variants x two arms,",
            "30 virtual days each. An evaluation operator approves exact pending hashes.",
            "This is approval-assisted, not unattended autonomy. No fixed-rule arm exists.",
            "Standard count targets are 200; infeasible targets exceed physical inventory.",
            "",
            "Each cell shows mean [p10 / p50 / p90]. CAC/spend are USD; margin is percent.",
            "Attainment and initial/final infeasibility are counts out of 100. Undefined CAC",
            "is excluded with its missing count, not filled with zero. Hard violations are",
            "dispatch/budget failures, distinct from observed economic guardrail breaches.",
            "",
            "| Scenario / variant / arm | Attained | CAC (missing) | Margin | Spend | Actions | "
            "Hard violations | Observed breaches | Infeasible initial/final |",
            "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
        ]
    )

    def dist(group: dict[str, Any], metric: str, scale: float = 1) -> str:
        values = group[metric]
        cells = [
            "undefined" if values[key] is None else f"{float(values[key]) * scale:.2f}"
            for key in ("mean", "p10", "p50", "p90")
        ]
        return f"{cells[0]} [{' / '.join(cells[1:])}]"

    for group in controller["summary"]:
        label = " / ".join(str(group[key]) for key in ("scenario", "variant", "arm"))
        cells = [
            label,
            str(group["objective_attained"]),
            f"{dist(group, 'cac_minor', 0.01)} ({group['cac_minor']['missing']})",
            dist(group, "contribution_margin", 100),
            dist(group, "spend_minor", 0.01),
            dist(group, "action_count"),
            dist(group, "hard_policy_violations"),
            dist(group, "outcome_guardrail_breaches"),
            f"{group['infeasible_detected_initially']}/{group['infeasible_detected_finally']}",
        ]
        lines.append("| " + " | ".join(cells) + " |")
    lines.extend(
        [
            "",
            "A goal can already be on track without an intervention. Acquisition standard",
            "outcomes must be read alongside the matched no-intervention arm. A synthetic",
            "difference is not causal merchant lift. Zero-action groups cannot establish",
            "safety or benefit for action paths they did not exercise.",
            "Zero hard-policy violations and zero benchmark rollbacks do not establish",
            "universal safety. Recovery/rollback paths are exercised separately in tests.",
            "[Full distributions, missing counts and profit](benchmarks/controller-v2-results.md).",
            "[Methods, exact raw rows and independent reproduction](benchmarks/controller-v2.md).",
            "",
            "## Reproduce",
            "",
            "From a bootstrapped checkout with matching host database/Qdrant settings:",
            "",
            "```bash",
            "make simulator-golden",
            "make benchmark-search",
            "uv run commerce-agent controller evaluate "
            "--verify examples/eval/results/controller-v2-durable.json.gz "
            "--output /tmp/controller-reproduction.json.gz",
            ".venv/bin/python scripts/render-preview-benchmarks.py --check",
            "```",
            "",
            "The full sweep takes hours and creates/removes only scratch benchmark databases.",
            "`make controller-eval-smoke` is a three-day smoke check, not full reproduction.",
            "Regenerate this document with the renderer without `--check`. Quality hashes",
            "exclude timing metadata. Original raw evidence is retained unchanged:",
            "",
            f"- Search: `{search['quality_evidence_hash']}`",
            f"- Controller: `{evidence.evidence_hash}`",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    report = render()
    if args.check:
        if OUTPUT.read_text() != report:
            raise SystemExit("Benchmark overview is stale; regenerate it")
    else:
        OUTPUT.write_text(report)


if __name__ == "__main__":
    main()
