"""Render the public benchmark table directly from recorded machine evidence."""

import json
from pathlib import Path


def main() -> None:
    source = Path("examples/eval/results/search-v2-live.json")
    data = json.loads(source.read_text(encoding="utf-8"))
    if data["retrieval_backend"] != "live_qdrant":
        raise ValueError("Public report requires live Qdrant evidence")
    lines = [
        "# Search Benchmark v2",
        "",
        "This is a small synthetic retrieval check, not production relevance evidence.",
        "",
        f"Generated measurement time: `{data['generated_at']}`.",
        f"Catalog: {data['catalog_count']} products, `{data['scenario']}`, seed {data['seed']}.",
        f"Queries: {data['query_count']} frozen judgments, including an impossible price query.",
        f"Backend: Qdrant {data['qdrant_version']}; client {data['qdrant_client_version']}; "
        f"Python {data['python_version']}.",
        "",
        "| Mode | NDCG@10 Mean | Recall@20 Mean | Hard Satisfaction "
        "| Latency p50 / p95 (ms) | Boosted Results |",
        "| --- | ---: | ---: | ---: | ---: | ---: |",
    ]
    for row in data["results"]:
        lines.append(
            f"| {row['mode']} | {row['ndcg_at_10']['mean']} | {row['recall_at_20']['mean']} "
            f"| {row['hard_constraint_satisfaction']} "
            f"| {row['latency_ms']['p50']} / {row['latency_ms']['p95']} "
            f"| {row['boosted_result_count']} |"
        )
    lines.extend(
        [
            "",
            "## Interpretation",
            "",
            "All modes are reported as measured. Reranking and boosts need not help relevance.",
            "The tiny legacy judgment set has incomplete labels, not statistical significance.",
            "One query returns no products; its recall/NDCG are zero in the aggregate.",
            "Hard satisfaction uses catalog variants and filters, not result self-reports.",
            "NDCG uses exponential gain (2^grade - 1) and logarithmic rank discount.",
            "Distributions use population standard deviation and interpolated percentiles.",
            "Latency includes embedding, retrieval and ranking, not indexing or API/PG loading.",
            "",
            "## Versions",
            "",
            f"- Catalog: `{data['catalog_version']}`",
            f"- Query set: `{data['query_set_version']}`",
            f"- Ranking: `{data['ranking_version']}`",
            f"- Template: `{data['document_template']}`",
            f"- Dense: `{data['embedding_model']}` (signed hashing, not a neural model)",
            f"- Sparse: `{data['sparse_model']}` (term frequency + IDF, not full BM25)",
            f"- Non-timing evidence: `{data['quality_evidence_hash']}`",
            "",
            "## Reproduce",
            "",
            "Run with the configured local Qdrant service healthy:",
            "",
            "```bash",
            "uv run commerce-agent eval search \\",
            "  --dataset examples/eval/search_queries_v2.jsonl \\",
            "  --verify examples/eval/results/search-v2-live.json \\",
            "  --output /tmp/search-reproduction.json",
            "```",
            "",
            "Verification compares quality and versions, not timestamps or latency.",
            "The isolated benchmark collection is deleted afterward. No commerce action runs.",
            "The bounded boost is a fixture. Executor and boost safety have integration tests.",
            "Five legacy queries are retained. A sixth uses all available outdoor Summit items",
            "as grade-3 judgments to exercise the boost scope, without consulting ranker output.",
            "Regenerate the dataset with `scripts/generate-search-dataset.py`.",
            "",
            "[Raw artifact](../../examples/eval/results/search-v2-live.json) contains each query.",
            "Generated by `scripts/render-search-report.py`; do not hand-edit measurement values.",
            "",
        ]
    )
    output = Path("docs/benchmarks/search-v2.md")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
